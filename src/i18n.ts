export function textForLanguage(
  item: { title?: string; title_ne?: string; name?: string; name_ne?: string },
  language: Language,
) {
  if (language === "ne") {
    return item.title_ne || item.name_ne || item.title || item.name || "";
  }
  return item.title || item.name || item.title_ne || item.name_ne || "";
}
